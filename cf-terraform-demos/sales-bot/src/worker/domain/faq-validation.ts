import { badRequest, notFound, unprocessableContent } from '@adrianhall/cloudflare-toolkit/errors';
import { isAudience } from './audience';
import type { CreateFaqInput, UpdateFaqInput } from './faq';

/**
 * Longest accepted question. Bounded so one entry cannot be used to store bulk text, and so the
 * retrieval prompt built in Phase 3 has a predictable upper size.
 */
const MAX_QUESTION_LENGTH = 500;

/**
 * Longest accepted answer. Generous enough for a real product answer with caveats, small enough
 * that a handful of retrieved FAQs still fit inside a bounded model context.
 */
const MAX_ANSWER_LENGTH = 8_000;

/**
 * Shape a product identifier must match: the lowercase slug used by the seeded product map.
 */
const PRODUCT_ID_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/u;

/**
 * Shape every FAQ identifier must match, as generated by `crypto.randomUUID()`.
 */
export const FAQ_ID_PATTERN =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/iu;

/**
 * Fields a caller may supply when creating an FAQ.
 */
const CREATE_FIELDS = ['question', 'answer', 'productId', 'audience', 'expiresAt'];

/**
 * Fields a caller may supply when editing an FAQ. `status` is editable so a PM can archive an
 * entry; `expired` is excluded by {@link validateStatus} because only maintenance writes it.
 */
const UPDATE_FIELDS = [...CREATE_FIELDS, 'status'];

/**
 * Ensure a parsed JSON value is a plain object.
 *
 * Arrays and `null` are rejected explicitly because both are `typeof "object"`, and letting either
 * through would produce a confusing `422` about a missing field instead of a clear `400` about the
 * body's shape.
 *
 * @param value Parsed JSON value from the request body.
 * @returns The same value narrowed to an object with string keys.
 * @throws {ProblemDetailsError} `badRequest()` (400) when the body is not a plain JSON object.
 */
function validateObject(value: unknown): Record<string, unknown> {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) {
    throw badRequest({ detail: 'The request body must be an object.' });
  }
  return value as Record<string, unknown>;
}

/**
 * Reject any property the endpoint does not accept.
 *
 * Unknown properties fail rather than being ignored, so a client that misspells `expiresAt` learns
 * about it instead of silently publishing an FAQ with the 90-day default it did not want.
 *
 * @param body Parsed request body.
 * @param allowed Property names this payload accepts.
 * @returns Nothing; it either passes or throws.
 * @throws {ProblemDetailsError} `unprocessableContent()` (422) when an unexpected property is
 *   present.
 */
function rejectUnknownFields(body: Record<string, unknown>, allowed: string[]): void {
  const unexpected = Object.keys(body).filter((key) => !allowed.includes(key));
  if (unexpected.length > 0) {
    throw unprocessableContent({
      detail: `Unexpected ${unexpected.length === 1 ? 'field' : 'fields'}: ${unexpected.join(', ')}.`
    });
  }
}

/**
 * Normalize and bound a free-text field.
 *
 * @param value Candidate text, straight from the untrusted request body.
 * @param field Field name used in the error message.
 * @param maxLength Longest accepted length after trimming.
 * @returns The trimmed text.
 * @throws {ProblemDetailsError} `unprocessableContent()` (422) when the value is not a string, is
 *   empty after trimming, or exceeds `maxLength`.
 */
function validateText(value: unknown, field: string, maxLength: number): string {
  if (typeof value !== 'string') {
    throw unprocessableContent({ detail: `${field} must be a string.` });
  }
  const text = value.trim();
  if (text.length === 0 || text.length > maxLength) {
    throw unprocessableContent({
      detail: `${field} must be between 1 and ${maxLength} characters.`
    });
  }
  return text;
}

/**
 * Validate an optional product reference.
 *
 * @param value Candidate product identifier, or `null` for a cross-product FAQ.
 * @returns The validated slug, or `null`.
 * @throws {ProblemDetailsError} `unprocessableContent()` (422) when the value is neither `null` nor
 *   a product slug.
 */
function validateProductId(value: unknown): string | null {
  if (value === null) {
    return null;
  }
  if (typeof value !== 'string' || !PRODUCT_ID_PATTERN.test(value)) {
    throw unprocessableContent({
      detail: 'productId must be null or a lowercase product slug such as "ai-gateway".'
    });
  }
  return value;
}

/**
 * Validate an audience classification.
 *
 * @param value Candidate audience from the request body.
 * @returns The validated audience.
 * @throws {ProblemDetailsError} `unprocessableContent()` (422) when the value is not one of the
 *   four defined audiences.
 */
function validateAudience(value: unknown): 'public' | 'customer' | 'nda' | 'internal' {
  if (!isAudience(value)) {
    throw unprocessableContent({
      detail: 'audience must be one of public, customer, nda, or internal.'
    });
  }
  return value;
}

/**
 * Validate an expiry instant.
 *
 * `null` is a meaningful value here, not an omission: it is how a PM removes the expiry from an FAQ
 * that genuinely does not go stale. Omitting the field instead leaves the stored value alone on an
 * edit, and applies the 90-day default on a create.
 *
 * @param value Candidate expiry from the request body.
 * @returns The instant normalized to ISO-8601, or `null` when the expiry was removed.
 * @throws {ProblemDetailsError} `unprocessableContent()` (422) when the value is neither `null` nor
 *   a parseable date-time string.
 */
function validateExpiresAt(value: unknown): string | null {
  if (value === null) {
    return null;
  }
  if (typeof value !== 'string') {
    throw unprocessableContent({ detail: 'expiresAt must be an ISO-8601 string or null.' });
  }
  const parsed = Date.parse(value);
  if (Number.isNaN(parsed)) {
    throw unprocessableContent({ detail: 'expiresAt must be a valid ISO-8601 instant.' });
  }
  return new Date(parsed).toISOString();
}

/**
 * Validate a caller-supplied lifecycle state.
 *
 * @param value Candidate status from the request body.
 * @returns The validated status.
 * @throws {ProblemDetailsError} `unprocessableContent()` (422) when the value is not `active` or
 *   `archived`. `expired` is rejected deliberately: it is a derived marker written by scheduled
 *   maintenance, and letting a client set it would make an FAQ look expired while its date says
 *   otherwise.
 */
function validateStatus(value: unknown): 'active' | 'archived' {
  if (value !== 'active' && value !== 'archived') {
    throw unprocessableContent({
      detail: 'status must be active or archived; expired is set by scheduled maintenance.'
    });
  }
  return value;
}

/**
 * Validate a publish-FAQ payload.
 *
 * @param value Parsed JSON body from the request.
 * @returns Validated creation input. `expiresAt` is present only when the caller supplied it, so
 *   the service can distinguish "no expiry" from "use the default".
 * @throws {ProblemDetailsError} `badRequest()` (400) when the body is not an object;
 *   `unprocessableContent()` (422) when a field is unknown, missing, or invalid.
 */
export function validateCreateFaqInput(value: unknown): CreateFaqInput {
  const body = validateObject(value);
  rejectUnknownFields(body, CREATE_FIELDS);
  const input: CreateFaqInput = {
    question: validateText(body.question, 'question', MAX_QUESTION_LENGTH),
    answer: validateText(body.answer, 'answer', MAX_ANSWER_LENGTH),
    productId: validateProductId(body.productId ?? null),
    audience: validateAudience(body.audience)
  };
  if (Object.hasOwn(body, 'expiresAt')) {
    input.expiresAt = validateExpiresAt(body.expiresAt);
  }
  return input;
}

/**
 * Validate an edit-FAQ payload.
 *
 * An empty object is rejected. An update that changes nothing would still have to load the FAQ to
 * answer, turning the endpoint into an existence oracle for identifiers the caller may not manage.
 *
 * @param value Parsed JSON body from the request.
 * @returns The validated mutable fields, with at least one present.
 * @throws {ProblemDetailsError} `badRequest()` (400) when the body is not an object;
 *   `unprocessableContent()` (422) when no field is supplied, or a supplied field is unknown or
 *   invalid.
 */
export function validateUpdateFaqInput(value: unknown): UpdateFaqInput {
  const body = validateObject(value);
  rejectUnknownFields(body, UPDATE_FIELDS);
  if (Object.keys(body).length === 0) {
    throw unprocessableContent({ detail: 'Supply at least one field to change.' });
  }

  const input: UpdateFaqInput = {};
  if (Object.hasOwn(body, 'question')) {
    input.question = validateText(body.question, 'question', MAX_QUESTION_LENGTH);
  }
  if (Object.hasOwn(body, 'answer')) {
    input.answer = validateText(body.answer, 'answer', MAX_ANSWER_LENGTH);
  }
  if (Object.hasOwn(body, 'productId')) {
    input.productId = validateProductId(body.productId);
  }
  if (Object.hasOwn(body, 'audience')) {
    input.audience = validateAudience(body.audience);
  }
  if (Object.hasOwn(body, 'expiresAt')) {
    input.expiresAt = validateExpiresAt(body.expiresAt);
  }
  if (Object.hasOwn(body, 'status')) {
    input.status = validateStatus(body.status);
  }
  return input;
}

/**
 * Validate an FAQ identifier taken from the request path.
 *
 * A malformed identifier raises `notFound()` rather than a validation error so that `404` and "you
 * may not manage this FAQ" are indistinguishable to a caller, and neither the status nor the body
 * reveals whether a well-formed identifier exists.
 *
 * @param id Candidate identifier from the URL path.
 * @returns The validated identifier.
 * @throws {ProblemDetailsError} `notFound()` (404) when the identifier is not a UUID.
 */
export function validateFaqId(id: string): string {
  if (!FAQ_ID_PATTERN.test(id)) {
    throw notFound({ detail: 'FAQ not found.' });
  }
  return id;
}
