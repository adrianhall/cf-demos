import { badRequest, notFound, unprocessableContent } from '@adrianhall/cloudflare-toolkit/errors';
import type { ClientFrame } from '../../chat-protocol';

/**
 * Longest accepted question.
 *
 * The same bound the FAQ question uses, and for the same reason: it keeps one submission from being
 * used as bulk storage, and it gives the retrieval prompt a predictable upper size. A salesperson's
 * question that genuinely needs more than 500 characters is a question for a person, which is what
 * the escalation path is for.
 */
export const MAX_QUESTION_LENGTH = 500;

/**
 * Longest accepted idempotency key.
 *
 * Long enough for a UUID or a hash, short enough that the key cannot smuggle a payload into the
 * uniqueness index. The pattern below additionally restricts it to characters that are safe to put
 * in a log line without escaping.
 */
const MAX_IDEMPOTENCY_KEY_LENGTH = 64;

/**
 * Shape an idempotency key must match.
 */
const IDEMPOTENCY_KEY_PATTERN = /^[\w-]{8,64}$/u;

/**
 * Shape every conversation identifier must match, as generated by `crypto.randomUUID()`.
 */
export const CONVERSATION_ID_PATTERN =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/iu;

/**
 * Fields an `ask` frame may carry.
 *
 * Note what is absent: there is no author, actor, identity, or clearance field. The requester is
 * pinned to the socket when it is accepted, so an unexpected field here is a client trying to
 * assert something it does not get to assert — which is why an unknown field is rejected rather
 * than ignored.
 */
const ASK_FIELDS = ['type', 'question', 'idempotencyKey'];

/**
 * Ensure a parsed value is a plain object.
 *
 * @param value Parsed JSON value.
 * @returns The same value narrowed to an object with string keys.
 * @throws {ProblemDetailsError} `badRequest()` (400) when the value is not a plain JSON object.
 *   Arrays and `null` are rejected explicitly because both are `typeof "object"`.
 */
function validateObject(value: unknown): Record<string, unknown> {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) {
    throw badRequest({ detail: 'The payload must be an object.' });
  }
  return value as Record<string, unknown>;
}

/**
 * Reject any property the frame does not accept.
 *
 * @param body Parsed frame.
 * @param allowed Property names this frame accepts.
 * @returns Nothing; it either passes or throws.
 * @throws {ProblemDetailsError} `unprocessableContent()` (422) when an unexpected property is
 *   present. An `author` or `identity` field fails here, which is the point.
 */
function rejectUnknownFields(body: Record<string, unknown>, allowed: string[]): void {
  const unexpected = Object.keys(body).filter((key) => !allowed.includes(key));
  if (unexpected.length > 0) {
    throw unprocessableContent({
      detail: `Unexpected ${unexpected.length === 1 ? 'field' : 'fields'}: ${unexpected.join(', ')}.`
    });
  }
}

/**
 * Validate and normalize a question.
 *
 * @param value Candidate question text, straight from the untrusted frame or request body.
 * @returns The trimmed question.
 * @throws {ProblemDetailsError} `unprocessableContent()` (422) when the value is not a string, is
 *   empty after trimming, or exceeds {@link MAX_QUESTION_LENGTH}.
 */
export function validateQuestion(value: unknown): string {
  if (typeof value !== 'string') {
    throw unprocessableContent({ detail: 'question must be a string.' });
  }
  const question = value.trim();
  if (question.length === 0 || question.length > MAX_QUESTION_LENGTH) {
    throw unprocessableContent({
      detail: `question must be between 1 and ${MAX_QUESTION_LENGTH} characters.`
    });
  }
  return question;
}

/**
 * Validate a client-supplied idempotency key.
 *
 * @param value Candidate key.
 * @returns The validated key.
 * @throws {ProblemDetailsError} `unprocessableContent()` (422) when the value is not a string of 8
 *   to {@link MAX_IDEMPOTENCY_KEY_LENGTH} word characters or hyphens.
 */
export function validateIdempotencyKey(value: unknown): string {
  if (typeof value !== 'string' || !IDEMPOTENCY_KEY_PATTERN.test(value)) {
    throw unprocessableContent({
      detail:
        `idempotencyKey must be 8 to ${MAX_IDEMPOTENCY_KEY_LENGTH} letters, digits, hyphens, or `
        + 'underscores.'
    });
  }
  return value;
}

/**
 * Validate a conversation identifier taken from a request path.
 *
 * A malformed identifier raises `notFound()` rather than a validation error so that `404` and "you
 * do not own this conversation" are indistinguishable to a caller: neither the status nor the body
 * reveals whether a well-formed identifier belongs to somebody else.
 *
 * @param id Candidate identifier from the URL path.
 * @returns The validated identifier.
 * @throws {ProblemDetailsError} `notFound()` (404) when the identifier is not a UUID.
 */
export function validateConversationId(id: string): string {
  if (!CONVERSATION_ID_PATTERN.test(id)) {
    throw notFound({ detail: 'Conversation not found.' });
  }
  return id;
}

/**
 * Validate an `ask` payload arriving over HTTP.
 *
 * Shared with the socket path below rather than duplicated, so a question is held to identical
 * rules whichever transport it arrived over. That is the whole reason validation lives in the
 * domain: a rule enforced in one transport and not the other is not a rule.
 *
 * @param value Parsed JSON body or frame payload.
 * @returns The validated question and idempotency key.
 * @throws {ProblemDetailsError} `badRequest()` (400) when the body is not an object;
 *   `unprocessableContent()` (422) when a field is unknown, missing, or invalid.
 */
export function validateAskInput(value: unknown): { question: string; idempotencyKey: string } {
  const body = validateObject(value);
  rejectUnknownFields(body, ASK_FIELDS);
  return {
    question: validateQuestion(body.question),
    idempotencyKey: validateIdempotencyKey(body.idempotencyKey)
  };
}

/**
 * Validate a frame arriving over the WebSocket.
 *
 * Every frame is validated here before anything acts on it, and the `ask` case reuses
 * {@link validateAskInput} so a question sent over a socket is bound and shaped exactly as one sent
 * over HTTP.
 *
 * @param value Parsed JSON value decoded from the frame.
 * @returns The validated frame.
 * @throws {ProblemDetailsError} `badRequest()` (400) when the payload is not an object;
 *   `unprocessableContent()` (422) when `type` is not a known frame, a field is unknown, or an
 *   `ask` frame's question or key is invalid.
 */
export function validateClientFrame(value: unknown): ClientFrame {
  const body = validateObject(value);
  switch (body.type) {
    case 'ask': {
      const input = validateAskInput(body);
      return { type: 'ask', ...input };
    }
    case 'cancel':
      rejectUnknownFields(body, ['type']);
      return { type: 'cancel' };
    case 'escalate':
      rejectUnknownFields(body, ['type']);
      return { type: 'escalate' };
    default:
      throw unprocessableContent({
        detail: 'type must be one of ask, cancel, or escalate.'
      });
  }
}
