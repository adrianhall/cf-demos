/**
 * @file Export filenames and the browser download that uses them. Both are deliberately
 *   browser-only concerns: a PNG or SVG of this canvas is a rasterisation of what the visitor's own
 *   browser laid out, which a Worker has no DOM to reproduce. The specification says so explicitly,
 *   and the later MCP layer therefore exposes JSON and project-scaffold exports rather than
 *   pretending a server can take a screenshot.
 */

/**
 * The file formats an export can produce a name for.
 */
export type ExportFormat = 'png' | 'svg' | 'zip';

/**
 * Builds an export filename from a diagram's title and the current time.
 *
 * The shape is `<sanitised-title>_<YYYY-MM-DD>_<HHmm>.<format>`. The timestamp is there because
 * exporting the same diagram twice is the common case — after a change, to compare — and two files
 * called `My_Architecture.png` in a downloads folder are indistinguishable.
 *
 * Sanitising is aggressive on purpose. A title is free text and reaches a filesystem here, so every
 * character outside `[A-Za-z0-9 ]` becomes an underscore rather than being passed through: that
 * covers path separators and the Windows-reserved set in one rule instead of a list to keep
 * current. Runs collapse and the edges are trimmed, so a title of punctuation cannot produce a name
 * that is all underscores.
 *
 * @param title Raw diagram title, sanitised before use.
 * @param format Extension to append.
 * @param now Clock reading for the stamp. Injected so a test asserts a fixed name rather than
 *   racing the real clock across a minute boundary; defaults to the current time.
 * @returns A filename safe to hand to a browser download, never empty and never extensionless — a
 *   blank or all-punctuation title falls back to `diagram`.
 */
export function generateExportFilename(
  title: string,
  format: ExportFormat,
  now: Date = new Date()
): string {
  const sanitized = title
    .replace(/[^a-zA-Z0-9 ]/gu, '_')
    .replace(/ /gu, '_')
    .replace(/_+/gu, '_')
    .replace(/^_+|_+$/gu, '');

  const name = sanitized || 'diagram';

  const year = now.getFullYear();
  const month = String(now.getMonth() + 1).padStart(2, '0');
  const day = String(now.getDate()).padStart(2, '0');
  const hours = String(now.getHours()).padStart(2, '0');
  const minutes = String(now.getMinutes()).padStart(2, '0');

  return `${name}_${year}-${month}-${day}_${hours}${minutes}.${format}`;
}

/**
 * Saves a generated file by triggering the browser's own download.
 *
 * A temporary, invisible `<a download>` is created, clicked and removed. That is the standard
 * client-side pattern for saving content the page produced rather than fetched: there is no URL a
 * real navigation could target, because the bytes exist only in this tab.
 *
 * The anchor is removed in the same turn it was clicked. The browser has already taken ownership of
 * the download by then, so leaving it attached would accumulate one dead element per export.
 *
 * @param url Data URL or object URL holding the generated bytes. The caller owns revoking an object
 *   URL afterwards; this function does not, because it cannot know whether the caller still needs
 *   it.
 * @param filename Name to save the file under, normally from {@link generateExportFilename}.
 * @returns Nothing. The download is the effect.
 */
export function triggerDownload(url: string, filename: string): void {
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
}
