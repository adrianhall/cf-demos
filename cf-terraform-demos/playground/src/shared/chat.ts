/**
 * @file The Chat panel's wire contract: the request the browser sends, and the typed events the
 *   Worker streams back. It sits at `src/` beside `tasks.ts` and `runs.ts` because both tiers need
 *   it, and it deliberately carries no model descriptors — the browser learns which models exist
 *   from `/api/catalogue`, and the Worker validates against its own reviewed list. A shared request
 *   _shape_ is useful; a shared model _list_ would let the browser decide what the server accepts.
 *   The stream events are a discriminated union on `type`, so a `switch` in the browser is checked
 *   for exhaustiveness and adding an event fails the build until the client handles it.
 */

import type { RunReceipt } from './runs.ts';

/**
 * Role of one message in a Chat conversation.
 *
 * `system` is absent on purpose. The system prompt is this panel's own, set server-side, so a
 * caller cannot supply one: accepting an arbitrary system prompt from a browser turns a narrow
 * "chat with a model" API into a general-purpose prompt proxy.
 */
export type ChatRole = 'user' | 'assistant';

/**
 * One turn of a conversation.
 */
export interface ChatMessage {
  /**
   * Who said it; see {@link ChatRole}.
   */
  role: ChatRole;
  /**
   * The message text.
   */
  content: string;
}

/**
 * What the browser posts to start a Chat run.
 *
 * Note what is _not_ here: no email, no user identifier, and no system prompt. The identity comes
 * from the verified Access JWT alone, and the domain rejects a body carrying an actor field rather
 * than ignoring it — an ignored field is one a later refactor can start trusting.
 */
export interface ChatRequest {
  /**
   * Conversation so far, ending with the user's new message.
   */
  messages: ChatMessage[];
  /**
   * Reviewed model identifier, which must be registered against the `chat` panel.
   */
  model: string;
  /**
   * Opaque run identifier generated by the browser, so the UI can correlate its own pending state
   * with the receipt before the first byte arrives.
   */
  runId: string;
  /**
   * Sampling temperature, when the visitor moved it off the model default.
   */
  temperature?: number;
  /**
   * Maximum tokens to generate, when the visitor set one.
   */
  maxTokens?: number;
}

/**
 * Sent once, before any model output, so the browser can show which model actually ran.
 *
 * The selected model is echoed rather than assumed: the browser asked for one, and this confirms
 * the server resolved that request to a reviewed descriptor.
 */
export interface ChatStartEvent {
  /**
   * Discriminant.
   */
  type: 'start';
  /**
   * Run this stream belongs to.
   */
  runId: string;
  /**
   * Model the server resolved and is about to call.
   */
  model: string;
}

/**
 * One increment of generated text.
 */
export interface ChatDeltaEvent {
  /**
   * Discriminant.
   */
  type: 'delta';
  /**
   * Text to append to what has arrived so far. Never a whole-answer replacement, so the browser
   * appends rather than re-rendering and cannot lose earlier text to a dropped frame.
   */
  text: string;
}

/**
 * Sent once when generation finished successfully, carrying the run receipt.
 *
 * The receipt arrives here rather than in a separate request because the gateway log identifier is
 * only known after the stream settles: the binding reports the identifier of its most recent call,
 * and reading it mid-stream would be reading it before there was anything to read.
 */
export interface ChatCompletedEvent {
  /**
   * Discriminant.
   */
  type: 'completed';
  /**
   * The run receipt, whose `costStatus` is `pending` whenever a gateway log exists to poll for.
   */
  receipt: RunReceipt;
}

/**
 * Sent instead of `completed` when the run failed.
 *
 * A failure is delivered as a typed event rather than by closing the stream, because a closed
 * stream is indistinguishable from a dropped connection. The payload is an RFC 9457 problem
 * document, the same shape every non-streaming failure uses, so the browser has one error path.
 */
export interface ChatProblemEvent {
  /**
   * Discriminant.
   */
  type: 'problem';
  /**
   * HTTP-equivalent status for the failure.
   */
  status: number;
  /**
   * Short, human-readable summary.
   */
  title: string;
  /**
   * Explanation safe to show a visitor. Never a provider message, which can carry prompt fragments
   * and internal endpoint names.
   */
  detail: string;
}

/**
 * Every event the Chat stream can emit.
 *
 * A stream always ends with exactly one of `completed` or `problem`. The browser treats the absence
 * of a terminal event as a dropped connection, which is a different situation from a failure the
 * server reported and is shown differently.
 */
export type ChatStreamEvent =
  | ChatStartEvent
  | ChatDeltaEvent
  | ChatCompletedEvent
  | ChatProblemEvent;

/**
 * Event names used on the wire, matching each event's `type` discriminant.
 *
 * Kept as a constant so the Worker's `event:` field and the browser's frame handling cannot drift:
 * a mismatch there would surface as a stream that silently produced no output.
 */
export const CHAT_EVENT_NAMES = ['start', 'delta', 'completed', 'problem'] as const;

/**
 * Longest single message the panel accepts, in characters.
 *
 * Part of the shared contract rather than server-only, so the editor can show a character counter
 * and refuse locally against the same number the server enforces. The server still validates
 * independently — a browser limit is a courtesy, never a control — but a visitor should not have to
 * send a request to discover a limit.
 */
export const MAX_MESSAGE_CHARACTERS = 8_000;

/**
 * Most conversation turns accepted in one request.
 *
 * Chat is specified as single-turn or short-history, and the bound is enforced rather than implied:
 * the whole conversation is re-sent on every turn and every token of it is charged for, so an
 * unbounded history is a cost that grows quadratically while looking like an ordinary chat. The
 * client trims to this length so a long conversation keeps working instead of starting to fail
 * validation.
 */
export const MAX_MESSAGES = 20;

/**
 * Lowest sampling temperature the panel will forward.
 */
export const MIN_TEMPERATURE = 0;

/**
 * Highest sampling temperature the panel will forward.
 *
 * The models' own schemas allow up to 5. The panel stops at 2 because the range above it produces
 * uniformly unusable output, and a control whose upper half only produces nonsense teaches
 * nothing.
 */
export const MAX_TEMPERATURE = 2;

/**
 * Smallest output token budget worth requesting.
 */
export const MIN_MAX_TOKENS = 16;

/**
 * Largest output token budget the panel will request.
 *
 * A ceiling on generated tokens is a ceiling on the cost of one click, which matters in a demo
 * anyone in the team can sign into.
 */
export const MAX_MAX_TOKENS = 2_048;
