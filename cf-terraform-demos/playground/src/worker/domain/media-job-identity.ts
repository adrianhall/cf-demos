/**
 * @file Derivation of a media job's identifier and storage key from the verified identity and the
 *   browser's run identifier. This is how the panel proves ownership without storing who owns what.
 *   A Workflow instance is already a durable, queryable job record, so adding a job table beside it
 *   would create two sources of truth for one status — and the usual consequence is a job that one
 *   store calls finished while the other calls it running. The remaining problem is that the status
 *   route must still refuse another visitor's job, which is normally what a stored owner column is
 *   for. Instead, the identifier _is_ the proof. It is a keyed hash of the verified email and the
 *   run identifier, so the route recomputes it from the identity on the current request: a
 *   different visitor asking for the same run identifier necessarily computes a different instance
 *   identifier, finds nothing, and receives a `404`. Ownership becomes unforgeable because it is
 *   not stored anywhere to be tampered with, and unenumerable because the digest space is far too
 *   large to walk. Two properties are load-bearing, and both are tested:
 *
 *   - **The same identity and run identifier must always derive the same value.** The job is started
 *     by one request and read by later ones, so a derivation that varied — by including a
 *     timestamp, say — would strand every job as unreadable the moment it was created.
 *   - **It must be keyed, not merely hashed.** A plain digest of an email and a run identifier could
 *     be computed by anyone who knows both, and a run identifier travels to the browser. The
 *     Workflow binding is not a secret store, so the key here is the Access audience tag: already
 *     bound to the Worker, already required to be correct for anything to work, and not something a
 *     visitor can read.
 */

/**
 * Prefix under which every generated video is stored.
 *
 * A single exported constant rather than a string literal at each call site, because two things
 * depend on it being exactly one value: the write guard asserting this demo stores nothing else in
 * the bucket, and the scheduled reaper in phase 18 that will delete only what lives under it. A
 * second spelling would silently create objects no reaper collects.
 */
export const GENERATED_VIDEO_PREFIX = 'generated-video/';

/**
 * Hex-encodes bytes.
 *
 * @param bytes Raw digest bytes.
 * @returns Lowercase hexadecimal.
 */
function toHex(bytes: Uint8Array): string {
  return Array.from(bytes, (byte) => byte.toString(16).padStart(2, '0')).join('');
}

/**
 * Derives the Workflow instance identifier for one visitor's run.
 *
 * Uses HMAC-SHA-256 over a field-separated message. The separator matters more than it looks: with
 * a bare concatenation, an email ending in a digit and a run identifier starting with one could
 * collide with a different pair, and a collision here means one visitor reading another's job. The
 * `\n` cannot appear in either field, so the split is unambiguous.
 *
 * @param email Verified email from the Access JWT. Must come from `currentIdentity()` and never
 *   from a request body or header — the whole ownership guarantee rests on this being verified.
 * @param runId Opaque run identifier generated by the browser.
 * @param key Secret keying material. The Access audience tag is used, because it is already bound
 *   to the Worker, is already required to be correct, and is not visible to a visitor.
 * @returns A lowercase hexadecimal instance identifier, safe for a Workflow instance ID (which
 *   permits alphanumerics, dashes, and underscores).
 * @throws {Error} When the email, run identifier, or key is empty, since each absence would
 *   silently weaken the derivation: an empty key reduces this to a guessable digest, and an empty
 *   email makes every visitor's jobs collide.
 */
export async function deriveMediaJobId(email: string, runId: string, key: string): Promise<string> {
  if (email === '' || runId === '' || key === '') {
    throw new Error('Media job identity requires a verified email, a run identifier, and a key.');
  }

  const encoder = new TextEncoder();
  const secret = await crypto.subtle.importKey(
    'raw',
    encoder.encode(key),
    { name: 'HMAC', hash: 'SHA-256' },
    false,
    ['sign']
  );
  const digest = await crypto.subtle.sign('HMAC', secret, encoder.encode(`${email}\n${runId}`));

  return toHex(new Uint8Array(digest));
}

/**
 * Builds the R2 object key for a derived job identifier.
 *
 * Derived from the job identifier rather than from the run identifier directly, so the key inherits
 * the same unguessability: someone who knows a run identifier still cannot name the object. Note
 * that this makes a key _identifying_ — it is a function of a verified email — which is why keys
 * are never written to a log, exactly as the email itself never is.
 *
 * @param jobId A job identifier from {@link deriveMediaJobId}.
 * @returns The object key, always under {@link GENERATED_VIDEO_PREFIX}.
 * @throws {Error} When the job identifier is empty, which would otherwise produce the prefix itself
 *   as a key and collide with every other such call.
 */
export function videoObjectKey(jobId: string): string {
  if (jobId === '') {
    throw new Error('A media job identifier is required to build a storage key.');
  }
  return `${GENERATED_VIDEO_PREFIX}${jobId}`;
}
