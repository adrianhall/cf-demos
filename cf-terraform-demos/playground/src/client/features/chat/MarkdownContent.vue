<script setup lang="ts">
import DOMPurify from 'dompurify';
import { marked, type Token } from 'marked';
/**
 * Renders one model response as GitHub-flavoured Markdown after sanitizing the generated HTML.
 *
 * Model output is untrusted input. A Markdown parser alone is not an HTML sanitizer: Markdown can
 * contain raw `<script>` tags, event-handler attributes, unsafe URLs, and ordinary HTML blocks.
 * `marked` handles the syntax and DOMPurify is the security boundary that makes the parser output
 * suitable for `v-html`. Keeping both operations in this one component means no other chat code has
 * to remember which half of the boundary it is holding.
 *
 * User messages do not pass through this component. They are rendered with escaped Vue
 * interpolation in {@link ChatTranscript}; Markdown is a presentation capability of model output,
 * not a way for a visitor's own input to become active HTML in the page.
 */
import { computed } from 'vue';

const props = defineProps<{
  /**
   * Markdown source generated by the model. It may be partial while a response streams.
   */
  source: string;
}>();

/**
 * Sanitized HTML ready to render.
 *
 * `marked.parse()` is configured synchronously because a streamed turn is re-rendered for every
 * delta and no asynchronous extension is installed. DOMPurify applies its normal HTML profile,
 * which keeps semantic Markdown output — headings, lists, links, code, tables — while removing
 * executable markup and unsafe attributes.
 */
const html = computed(() => {
  const parsed = marked.parse(props.source, {
    async: false,
    breaks: true,
    gfm: true,
    // A model's `# Heading` belongs inside one assistant turn, beneath the page's real h1 and the
    // conversation context. Shift every Markdown heading down two levels so generated content can
    // never introduce a rival page heading; clamp at h6 for deep source outlines.
    walkTokens: (token: Token) => {
      if (token.type === 'heading') {
        token.depth = Math.min(token.depth + 2, 6) as 1 | 2 | 3 | 4 | 5 | 6;
      }
    }
  });

  return DOMPurify.sanitize(parsed, {
    // Strict allowlist rather than a denylist. DOMPurify's default profile also permits media and
    // form elements; a model could otherwise emit `<video poster="https://tracker/...">` to cause
    // a third-party request, or a convincing form that posts to an arbitrary origin. This panel
    // needs only the semantic elements Markdown itself produces.
    ALLOWED_ATTR: ['align', 'checked', 'colspan', 'disabled', 'href', 'rowspan', 'title', 'type'],
    ALLOWED_TAGS: [
      'a',
      'blockquote',
      'br',
      'code',
      'del',
      'em',
      'h1',
      'h2',
      'h3',
      'h4',
      'h5',
      'h6',
      'hr',
      'input',
      'li',
      'ol',
      'p',
      'pre',
      'strong',
      'table',
      'tbody',
      'td',
      'th',
      'thead',
      'tr',
      'ul'
    ]
  });
});
</script>

<template>
  <!-- eslint-disable-next-line vue/no-v-html -- `html` is sanitized by DOMPurify above. -->
  <div
    class="markdown"
    role="group"
    aria-label="Formatted assistant response"
    tabindex="0"
    v-html="html"
  ></div>
</template>

